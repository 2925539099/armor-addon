def main() -> None:
    text = CL.read_text(encoding="utf-8")

    if "## [1.4.0]" not in text:
        text = text.replace("## [1.3.4]", ENTRY, 1)
        print("  已插入 1.4.0 条目")
    else:
        print("  1.4.0 已存在，跳过")

    if "[1.4.0]: " not in text:
        link = "[1.4.0]: https://github.com/2925539099/armor-addon/compare/v1.3.4...v1.4.0\n[1.3.4]: "
